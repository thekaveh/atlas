"""Supabase db guards: the pg_hba SCRAM rewrite and the decommission drops.

The host-auth tests run the shell guard against a temporary data directory with
a stub entrypoint. The decommission tests run the two shape-guarded drops
against a throwaway postgres:17-alpine container, and skip when docker or that
image is not available locally.
"""

