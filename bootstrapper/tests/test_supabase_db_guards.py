# ---- pg_hba SCRAM rewrite (no docker) ------------------------------------

def _run_host_auth(tmp_path: Path, hba: str, args: list[str]) -> subprocess.CompletedProcess:
    pgdata = tmp_path / "pgdata"
    pgdata.mkdir()
    (pgdata / "PG_VERSION").write_text("17\n")
    (pgdata / "pg_hba.conf").write_text(hba)
    stub = tmp_path / "entrypoint.sh"
    stub.write_text('#!/bin/sh\necho "ENTRYPOINT $*"\n')
    stub.chmod(0o755)
    env = {"PGDATA": str(pgdata), "ATLAS_POSTGRES_ENTRYPOINT": str(stub), "PATH": "/usr/bin:/bin"}
    return subprocess.run(
        ["sh", str(HOST_AUTH), *args], env=env, capture_output=True, text=True, timeout=30,
    )


MASK_HBA = """local all supabase_admin trust
host all all 10.0.0.0 255.0.0.0 trust
host all all 192.168.1.0 255.255.255.0 password
host all all 172.16.0.0/12 trust
host all all 0.0.0.0/0 scram-sha-256
"""


def test_host_auth_rewrites_netmask_form_when_data_dir_is_used(tmp_path):
    result = _run_host_auth(tmp_path, MASK_HBA, ["-c", "x=1"])
    assert result.returncode == 0, result.stderr
    rewritten = (tmp_path / "pgdata" / "pg_hba.conf").read_text().splitlines()
    assert rewritten[0] == "local all supabase_admin trust"
    assert rewritten[1].split() == ["host", "all", "all", "10.0.0.0", "255.0.0.0", "scram-sha-256"]
    assert rewritten[2].split() == ["host", "all", "all", "192.168.1.0", "255.255.255.0", "scram-sha-256"]
    assert rewritten[3].split()[-1] == "scram-sha-256"
    assert rewritten[4].split()[-1] == "scram-sha-256"
    assert "ENTRYPOINT postgres -c x=1" in result.stdout


def test_host_auth_refuses_netmask_md5_when_data_dir_is_used(tmp_path):
    hba = "host all all 10.0.0.0 255.0.0.0 md5\n"
    result = _run_host_auth(tmp_path, hba, [])
    assert result.returncode == 1
    assert "refusing pg_hba.conf upgrade" in result.stderr
    assert (tmp_path / "pgdata" / "pg_hba.conf").read_text() == hba


def test_host_auth_with_image_config_flag_rewrites_only_unused_file(tmp_path):
    # Compose passes -D /etc/postgresql. The guard still rewrites the
    # data-directory copy, which the server does not read, and passes the flag on.
    hba = "host all all 10.0.0.0 255.0.0.0 trust\n"
    result = _run_host_auth(tmp_path, hba, ["-D", "/etc/postgresql", "-c", "x=1"])
    assert result.returncode == 0, result.stderr
    rewritten = (tmp_path / "pgdata" / "pg_hba.conf").read_text()
    assert rewritten.split()[-1] == "scram-sha-256"
    assert "ENTRYPOINT postgres -D /etc/postgresql -c x=1" in result.stdout


# ---- decommission drops (docker-gated) -----------------------------------

def _docker_ready() -> bool:
    if shutil.which("docker") is None:
        return False
    probe = subprocess.run(
        ["docker", "image", "inspect", PG_IMAGE], capture_output=True, timeout=30,
    )
    return probe.returncode == 0


pytestmark_docker = pytest.mark.skipif(
    not _docker_ready(), reason=f"docker or the local {PG_IMAGE} image is not available",
)


@pytest.fixture(scope="module")
def pg_container():
    if not _docker_ready():
        pytest.skip(f"docker or the local {PG_IMAGE} image is not available")
    name = f"atlas-guard-test-{uuid.uuid4().hex[:8]}"
    subprocess.run(
        ["docker", "run", "-d", "--rm", "--name", name, "-e", "POSTGRES_PASSWORD=test", PG_IMAGE],
        check=True, capture_output=True, timeout=120,
    )
    try:
        deadline = time.monotonic() + 90
        while True:
            ready = subprocess.run(
                ["docker", "exec", name, "pg_isready", "-U", "postgres"], capture_output=True,
            )
            if ready.returncode == 0:
                break
            if time.monotonic() > deadline:
                pytest.fail("postgres container did not become ready")
            time.sleep(1)
        yield name
    finally:
        subprocess.run(["docker", "rm", "-f", name], capture_output=True, timeout=60)


def _psql(container: str, sql: str) -> str:
    result = subprocess.run(
        ["docker", "exec", "-i", container, "psql", "-U", "postgres", "-d", "postgres",
         "-v", "ON_ERROR_STOP=1", "-q", "-t", "-A", "-f", "-"],
        input=sql, capture_output=True, text=True, timeout=120,
    )
    assert result.returncode == 0, result.stderr
    return result.stdout


def _exists(container: str, table: str) -> bool:
    out = _psql(container, f"SELECT to_regclass('public.{table}') IS NOT NULL;")
    return out.strip() == "t"


def _reset(container: str):
    _psql(container, "DROP TABLE IF EXISTS public.llms; DROP TABLE IF EXISTS public.comfyui_models;")


@pytestmark_docker
def test_llms_drop_is_absent_table_noop(pg_container):
    _reset(pg_container)
    _psql(pg_container, LLMS_DROP.read_text())
    assert not _exists(pg_container, "llms")


@pytestmark_docker
def test_llms_drop_removes_atlas_shaped_table(pg_container):
    _reset(pg_container)
    _psql(pg_container, LLMS_DDL)
    _psql(pg_container, LLMS_DROP.read_text())
    assert not _exists(pg_container, "llms")


@pytestmark_docker
def test_llms_drop_keeps_consumer_table_with_other_shape(pg_container):
    _reset(pg_container)
    _psql(pg_container, "CREATE TABLE public.llms (id int primary key, payload text);")
    _psql(pg_container, LLMS_DROP.read_text())
    assert _exists(pg_container, "llms")


@pytestmark_docker
def test_llms_drop_keeps_near_miss_shapes(pg_container):
    _reset(pg_container)
    _psql(pg_container, LLMS_DDL.replace("  api_endpoint text,\n", ""))
    _psql(pg_container, LLMS_DROP.read_text())
    assert _exists(pg_container, "llms")
    _psql(pg_container, "DROP TABLE public.llms;")
    _psql(pg_container, LLMS_DDL.replace("  api_endpoint text,\n", "  api_endpoint text,\n  extra text,\n"))
    _psql(pg_container, LLMS_DROP.read_text())
    assert _exists(pg_container, "llms")


